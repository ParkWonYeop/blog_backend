CREATE TABLE mcp_key (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member(id),
    name VARCHAR(100) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    token_prefix VARCHAR(13) NOT NULL,
    permission VARCHAR(20) NOT NULL CHECK (permission IN ('READ_ONLY', 'READ_WRITE')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT mcp_key_expiry CHECK (expires_at > created_at)
);

CREATE INDEX idx_mcp_key_member_created ON mcp_key(member_id, created_at DESC, id DESC);
